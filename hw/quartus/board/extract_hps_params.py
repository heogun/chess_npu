#!/usr/bin/env python3
"""Write hps_params.tcl from the HPS instance of a known DE1-SoC Platform Designer system.

Source: https://github.com/VCTLabs/DE1_SOC_Linux_FB, the project U-Boot's doc/README.socfpga cites.
Only pin muxing, clocks and memory settings are taken. Fabric interfaces are set in soc.tcl.
Usage: extract_hps_params.py <soc_system.qsys> <hps_params.tcl>
"""
import re
import sys
import xml.etree.ElementTree as ET

KEEP = re.compile(r"^(MEM_|TIMING_|.*_PinMuxing$|.*_Mode$|GPIO_Enable$|LOANIO_Enable$|HPS_PROTOCOL$|REF_CLK_FREQ$|BSEL$|CSEL$"
                  r"|desired_|.*_clk_div$|.*_clk_source$|main_pll_|periph_pll_|eosc\d_clk_mhz$|use_default_mpu_clk$|dbctrl_stayosc1$"
                  r"|RATE$|SPEED_GRADE$|PLL_MEM_CLK|TRFC$|TREFI$|DAT_DATA_WIDTH$)")
SKIP = re.compile(r"_DERIVED$|^MEM_DEVICE$|^desired_.*_hz_DERIVED")


def main(src, out):
    root = ET.parse(src).getroot()
    hps = next(m for m in root.findall("module") if m.get("kind") == "altera_hps")
    lines = ["# Generated by extract_hps_params.py. HPS pin muxing, clocks and memory settings.", "set hps_params {"]
    for p in hps.findall("parameter"):
        name = p.get("name")
        value = p.get("value")
        if value is None:
            value = (p.text or "").strip()
        if value == "" or not KEEP.match(name) or SKIP.search(name):
            continue
        lines.append("    {%s} {%s}" % (name, value))
    lines.append("}")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 3} parameters")


if __name__ == "__main__":
    main(*sys.argv[1:])
